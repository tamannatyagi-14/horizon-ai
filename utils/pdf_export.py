"""Export a finished run as a clean PDF "content pack" (reportlab).

Standard PDF fonts cover Western characters (curly quotes, em dashes) but not
emojis, so unsupported characters are dropped from the PDF text.
"""
from io import BytesIO
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.enums import TA_LEFT
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import HRFlowable, KeepTogether, Paragraph, SimpleDocTemplate, Spacer

PURPLE = colors.HexColor("#7C3AFF")
INK = colors.HexColor("#1A1A2E")
MUTED = colors.HexColor("#6B6B8A")
BOX = colors.HexColor("#F4F5FA")
LINE = colors.HexColor("#DADCEB")
NAMES = {"linkedin": "LinkedIn", "instagram": "Instagram", "twitter": "Twitter / X"}


def _clean(text) -> str:
    """Keep only what the built-in PDF fonts can draw."""
    return str(text or "").encode("cp1252", "ignore").decode("cp1252")


def _p(text) -> str:
    return escape(_clean(text)).replace("\n", "<br/>")


def build_pdf(meta: dict, posts: dict, slop=None, engagement=None, rules=None) -> bytes:
    """meta: topic, tone, mode, date, retries, cost, fact_check_passed. posts: {platform: text}."""
    buf = BytesIO()
    doc = SimpleDocTemplate(
        buf, pagesize=A4, leftMargin=20 * mm, rightMargin=20 * mm,
        topMargin=18 * mm, bottomMargin=18 * mm, title="Horizon AI content pack", author="Horizon AI",
    )
    h_title = ParagraphStyle("t", fontName="Helvetica-Bold", fontSize=22, leading=26, textColor=INK)
    h_sub = ParagraphStyle("s", fontName="Helvetica", fontSize=10, leading=14, textColor=MUTED)
    h_topic = ParagraphStyle("tp", fontName="Helvetica-Bold", fontSize=13, leading=17, textColor=INK, spaceBefore=10)
    h_sec = ParagraphStyle("h", fontName="Helvetica-Bold", fontSize=12, leading=16, textColor=PURPLE, spaceBefore=14, spaceAfter=5)
    h_plat = ParagraphStyle("hp", parent=h_sec, spaceBefore=10, spaceAfter=14)  # room for the box padding
    body = ParagraphStyle(
        "b", fontName="Helvetica", fontSize=10.5, leading=15.5, textColor=INK, alignment=TA_LEFT,
        backColor=BOX, borderColor=LINE, borderWidth=0.6, borderPadding=9, borderRadius=4,
        spaceBefore=6, spaceAfter=12,
    )
    small = ParagraphStyle("sm", fontName="Helvetica", fontSize=9.5, leading=14, textColor=INK)

    story = [
        Paragraph("Horizon AI", h_title),
        Paragraph("Every idea deserves a bigger horizon", h_sub),
        HRFlowable(width="100%", thickness=0.8, color=PURPLE, spaceBefore=8, spaceAfter=2),
        Paragraph(_p(meta.get("topic", "")), h_topic),
        Paragraph(
            _p(
                f"{meta.get('date', '')}  |  Tone: {meta.get('tone', '')}  |  Mode: {meta.get('mode', '')}  |  "
                f"Editor retries: {meta.get('retries', 0)}  |  Fact-check: "
                f"{'passed' if meta.get('fact_check_passed') else 'flagged'}"
            ),
            h_sub,
        ),
    ]

    score_bits = []
    if slop:
        score_bits.append(f"<b>Human feel:</b> {slop['human_score']}/100")
        if slop.get("flagged"):
            score_bits.append("<b>Flagged phrases:</b> " + _p(", ".join(slop["flagged"][:5])))
    if engagement:
        score_bits.append(
            f"<b>Virality:</b> {engagement['virality']}/100 "
            f"(hook {engagement['hook']['label']}, CTA {engagement['cta']['label']}, "
            f"emotion {engagement['emotion']['label']})"
        )
        if engagement.get("tip"):
            score_bits.append("<b>Tip:</b> " + _p(engagement["tip"]))
    if score_bits:
        story += [Paragraph("Scores", h_sec)] + [Paragraph(b, small) for b in score_bits]

    if rules:
        story.append(Paragraph("Strategy applied", h_sec))
        story += [Paragraph("- " + _p(r), small) for r in rules]

    for key, text in posts.items():
        if not text:
            continue
        story.append(KeepTogether([Paragraph(NAMES.get(key, key.title()), h_plat), Paragraph(_p(text), body)]))

    story.append(Spacer(1, 6))
    story.append(Paragraph(_p(f"Estimated cost of this run: ${meta.get('cost', 0):.4f}"), h_sub))

    def footer(canvas, d):
        canvas.saveState()
        canvas.setFont("Helvetica", 8)
        canvas.setFillColor(MUTED)
        canvas.drawString(20 * mm, 10 * mm, "Generated by Horizon AI")
        canvas.drawRightString(A4[0] - 20 * mm, 10 * mm, f"Page {d.page}")
        canvas.restoreState()

    doc.build(story, onFirstPage=footer, onLaterPages=footer)
    return buf.getvalue()